CREATE DATABASE IF NOT EXISTS ubuntu_health_ai CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ubuntu_health_ai;

CREATE TABLE IF NOT EXISTS symptom_checks (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 symptom VARCHAR(80) NOT NULL,
 duration VARCHAR(40) NOT NULL,
 severity VARCHAR(30) NOT NULL,
 guidance_level VARCHAR(80) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS chatbot_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 question VARCHAR(500) NOT NULL,
 answer_category VARCHAR(80) NOT NULL DEFAULT 'general',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS appointment_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL,
 phone VARCHAR(40) NULL,
 facility VARCHAR(150) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 status ENUM('new','reviewing','contacted','closed') NOT NULL DEFAULT 'new',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_appointment_status (status),
 INDEX idx_appointment_created (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS contact_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL,
 message VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
